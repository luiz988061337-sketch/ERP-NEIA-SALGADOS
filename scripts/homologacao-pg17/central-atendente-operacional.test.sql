CREATE FUNCTION public.has_role(id uuid, papel public.app_role) RETURNS boolean LANGUAGE sql STABLE AS $$
  SELECT coalesce(right(id::text, 2) = CASE papel
    WHEN 'admin' THEN '10' WHEN 'atendente' THEN '11' WHEN 'producao' THEN '12'
    WHEN 'motoboy' THEN '13' WHEN 'financeiro' THEN '16' END, false);
$$;
