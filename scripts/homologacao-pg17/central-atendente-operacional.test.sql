CREATE POLICY base_pedido ON public.pedidos FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR motoboy_id = auth.uid()
    OR has_role(auth.uid(),'atendente') OR has_role(auth.uid(),'producao')
    OR has_role(auth.uid(),'admin') OR has_role(auth.uid(),'financeiro'));
CREATE POLICY base_criar_pedido ON public.pedidos FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.uid());
CREATE POLICY base_atualizar_pedido ON public.pedidos FOR UPDATE TO authenticated
  USING (has_role(auth.uid(),'admin') OR has_role(auth.uid(),'producao'))
  WITH CHECK (has_role(auth.uid(),'admin') OR has_role(auth.uid(),'producao'));
CREATE POLICY base_item ON public.pedido_itens FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.pedidos p WHERE p.id = pedido_id
    AND (p.user_id = auth.uid() OR p.motoboy_id = auth.uid()
      OR has_role(auth.uid(),'producao') OR has_role(auth.uid(),'admin'))));
CREATE POLICY base_componentes ON public.pedido_item_componentes FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.pedido_itens i JOIN public.pedidos p ON p.id = i.pedido_id
    WHERE i.id = pedido_item_id AND (p.user_id = auth.uid() OR p.motoboy_id = auth.uid()
       OR has_role(auth.uid(),'atendente') OR has_role(auth.uid(),'producao') OR has_role(auth.uid(),'admin'))
  ));
CREATE POLICY base_remessas ON public.producao_remessas FOR SELECT TO authenticated
  USING (has_role(auth.uid(),'admin') OR has_role(auth.uid(),'producao'));
CREATE POLICY base_avisos_leitura ON public.notificacoes FOR SELECT TO authenticated
  USING (has_role(auth.uid(),'admin') OR has_role(auth.uid(),'atendente')
    OR has_role(auth.uid(),'producao') OR has_role(auth.uid(),'motoboy') OR has_role(auth.uid(),'financeiro'));
CREATE POLICY base_avisos_envio ON public.notificacoes FOR INSERT TO authenticated
  WITH CHECK (has_role(auth.uid(),'admin') OR has_role(auth.uid(),'atendente')
    OR has_role(auth.uid(),'producao') OR has_role(auth.uid(),'motoboy') OR has_role(auth.uid(),'financeiro'));
