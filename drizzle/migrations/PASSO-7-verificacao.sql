  (SELECT coalesce(string_agg(id, ', ' ORDER BY id), 'NENHUM') FROM storage.buckets) AS "3_BUCKETS",
  (SELECT count(*)::text FROM pg_proc WHERE pronamespace = 'public'::regnamespace) AS "4_FUNCOES";

